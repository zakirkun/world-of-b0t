'use strict';

const path = require('path');
const fs = require('fs');
const crypto = require('crypto');
const express = require('express');
const Database = require('better-sqlite3');

const PORT = Number(process.env.PORT || 30000);
const DB_PATH = process.env.DB_PATH || path.join(__dirname, 'data', 'scoreboard.db');
const FLAGS_PATH = process.env.FLAGS_PATH || path.join(__dirname, 'data', 'flags.json');

fs.mkdirSync(path.dirname(DB_PATH), { recursive: true });

const db = new Database(DB_PATH);
db.pragma('journal_mode = WAL');

db.exec(`
  CREATE TABLE IF NOT EXISTS solves (
    id        INTEGER PRIMARY KEY AUTOINCREMENT,
    lab       TEXT    NOT NULL,
    team      TEXT    NOT NULL,
    flag_hash TEXT    NOT NULL,
    points    INTEGER NOT NULL DEFAULT 0,
    created_at TEXT   NOT NULL
  );
  CREATE UNIQUE INDEX IF NOT EXISTS idx_solves_lab_team ON solves(lab, team);
  CREATE INDEX IF NOT EXISTS idx_solves_team ON solves(team);

  -- Authoritative flag store. The launcher writes .secrets/flags.json; the
  -- scoreboard syncs it here at boot and on reload, and submit verifies against
  -- THIS table, not the JSON file. One row per lab.
  CREATE TABLE IF NOT EXISTS flags (
    lab        TEXT PRIMARY KEY,
    flag_hash  TEXT NOT NULL,
    updated_at TEXT NOT NULL
  );
`);

// ---------------------------------------------------------------------------
// Flags
// ---------------------------------------------------------------------------
// .secrets/flags.json is generated by the launcher at `up` time:
//   { "w01": "hex4b0t{...}", "w02": "hex4b0t{...}", ... }
// The scoreboard syncs it into the `flags` table. Only a sha256 hash is stored;
// plaintext never persists in the database.
//
// ponytail: flags.json stays the launcher's source of truth and the table is a
// derived cache - that keeps manual per-lab rotation working through the same
// one file both launchers already write.
function loadFlags() {
  let raw = {};
  try {
    raw = JSON.parse(fs.readFileSync(FLAGS_PATH, 'utf8'));
  } catch {
    raw = {};
  }
  const now = new Date().toISOString();
  const up = db.prepare(
    `INSERT INTO flags (lab, flag_hash, updated_at) VALUES (?, ?, ?)
     ON CONFLICT(lab) DO UPDATE SET flag_hash = excluded.flag_hash, updated_at = excluded.updated_at`
  );
  const sync = db.transaction((entries) => {
    for (const [lab, flag] of entries) up.run(lab, hash(flag), now);
  });
  sync(Object.entries(raw).filter(([lab, flag]) => lab && typeof flag === 'string'));
  return raw;
}

// Every flag read goes through the table; the JSON file is never consulted here.
const flagCount = () => db.prepare('SELECT COUNT(*) AS n FROM flags').get().n;

const hash = (s) => crypto.createHash('sha256').update(String(s)).digest('hex');

const POINTS = {
  easy: 100,
  medium: 250,
  hard: 500,
};

let LABS = [];
try {
  LABS = JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'labs.json'), 'utf8')).labs;
} catch {
  LABS = [];
}
const labById = new Map(LABS.map((l) => [l.id, l]));
// Score is a property of difficulty, not of the lab row. Expose it so the web
// UI, the API, and the MCP tools all report the same number.
const pointsFor = (lab) => POINTS[labById.get(lab)?.difficulty] || POINTS.easy;
const labPoints = () => Object.fromEntries(LABS.map((l) => [l.id, pointsFor(l.id)]));

loadFlags();

